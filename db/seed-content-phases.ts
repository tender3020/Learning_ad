/**
 * 每日内容生成 · 按大纲阶段细分的 Prompt 片段
 * component_key 约定：
 * - 默认：phase:content:{typeKey}:{order}
 * - 模型应用型轮换：phase:content:model_apply:{order}:{A|B}
 * 与 shared/outlinePhases.ts 阶段一一对应
 */

export type PhaseContentSeed = {
  key: string;
  typeKey: string;
  title: string;
  content: string;
};

function p(typeKey: string, order: number, title: string, content: string): PhaseContentSeed {
  return { key: `phase:content:${typeKey}:${order}`, typeKey, title, content };
}

/** 模型应用型同阶段 A/B 侧重点轮换 */
function pv(
  typeKey: string,
  order: number,
  variant: "A" | "B",
  title: string,
  content: string,
): PhaseContentSeed {
  return { key: `phase:content:${typeKey}:${order}:${variant}`, typeKey, title, content };
}

